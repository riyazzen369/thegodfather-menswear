from PIL import Image, ImageFilter
import glob, os, base64, io, json
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'public'))
os.makedirs('img/r', exist_ok=True)
lq = {}
for f in sorted(glob.glob('img/*.webp')):
    name = os.path.basename(f)[:-5]
    im = Image.open(f).convert('RGB')
    w, h = im.size
    for W in (512, w):
        r = im if W == w else im.resize((W, round(h * W / w)), Image.LANCZOS)
        tag = 'full' if W == w else str(W)
        r.save(f'img/r/{name}-{tag}.avif', quality=58, speed=6)
        if W != w: r.save(f'img/r/{name}-{tag}.webp', quality=80, method=6)
    t = im.resize((12, 16), Image.LANCZOS)
    b = io.BytesIO(); t.save(b, 'WEBP', quality=50)
    lq[name] = 'data:image/webp;base64,' + base64.b64encode(b.getvalue()).decode()
open('../src/lqip.ts', 'w').write('// generated by scripts/imgs.py: 12x16 previews for the blur-up placeholders\nexport const LQIP: Record<string, string> = ' + json.dumps(lq, indent=0) + '\n')
lg = Image.open('brand/logo.png').convert('RGBA')
for W in (160, 240, 320, 800):
    r = lg.resize((W, round(1180 * W / 1550)), Image.LANCZOS)
    if W <= 320: r = r.filter(ImageFilter.UnsharpMask(radius=0.6, percent=60, threshold=1))
    r.save(f'brand/logo-{W}.webp', quality=92, method=6)
    r.save(f'brand/logo-{W}.png', optimize=True)
print(len(lq))
